export type GuideSectionHighlight = {
  label: string;
  value: string;
};

export type GuideSection = {
  title: string;
  body: string;
  paragraphs?: string[];
  image?: string;
  imageCaption?: string;
  highlights?: GuideSectionHighlight[];
};

export type Guide = {
  slug: string;
  category: string;
  title: string;
  excerpt: string;
  keyword: string;
  vehicle?: string;
  region?: string;
  tag: string;
  sections: GuideSection[];
  status: 'sample' | 'draft' | 'published';
  image?: string;
  publishedAt?: string;
  updatedAt?: string;
  author?: string;
  reviewedBy?: string;
  sources?: { title: string; url: string }[];
  relatedLinks?: { title: string; url: string }[];
  postCategories?: PostCategorySlug[];
};

export function guideMatchesPostCategory(
  guide: Guide,
  category: PostCategorySlug,
) {
  if (guide.postCategories?.length)
    return guide.postCategories.includes(category);
  if (category === 'blog')
    return (
      guide.category === 'blog' ||
      /블로그|상식|팁|관리/.test(`${guide.keyword} ${guide.title}`)
    );
  if (category === 'vehicles')
    return Boolean(guide.vehicle) || guide.category === 'vehicles';
  if (category === 'cost')
    return (
      guide.category === 'service' ||
      /비용|가격|수명|교체/.test(`${guide.keyword} ${guide.title}`)
    );
  return /방전|시동|점프|긴급/.test(
    `${guide.keyword} ${guide.title} ${guide.tag}`,
  );
}
